// Regenerates docs/repo-map.md: a tree of packages with one line each (from package.json / Cargo.toml descriptions).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const rows: string[] = [];

function describe(dir: string): string | undefined {
  const pkg = join(dir, "package.json");
  if (existsSync(pkg)) return (JSON.parse(readFileSync(pkg, "utf8")) as { description?: string }).description;
  const cargo = join(dir, "Cargo.toml");
  if (existsSync(cargo)) return /^description\s*=\s*"(.*)"/m.exec(readFileSync(cargo, "utf8"))?.[1];
  return undefined;
}

function walk(base: string, depth: number) {
  for (const name of readdirSync(join(root, base)).sort()) {
    const rel = `${base}/${name}`;
    const abs = join(root, rel);
    if (!existsSync(join(abs, "package.json")) && !existsSync(join(abs, "Cargo.toml"))) {
      if (depth < 2 && !name.startsWith(".") && name !== "node_modules") {
        try {
          walk(rel, depth + 1);
        } catch {}
      }
      continue;
    }
    rows.push(`- \`${rel}\` — ${describe(abs) ?? ""}`);
  }
}

for (const top of ["crates", "packages", "apps"]) walk(top, 0);
writeFileSync(
  join(root, "docs/repo-map.md"),
  `# Repo map\n\n_Generated by \`pnpm repo:map\`. Do not edit by hand._\n\n${rows.join("\n")}\n`,
);
console.log(`wrote docs/repo-map.md (${rows.length} packages)`);
